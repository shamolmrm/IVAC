"""Read the Indian online visa application form (the "BGD…" PDF) into applicant fields.

The PDF is generated by the official portal and has a text layer, so no OCR is needed:
``pdftotext -layout`` keeps each label and its value on one line, separated by wide gaps.
Labels below are the ones printed on the form; a field whose label is missing stays empty.
"""

import re
import shutil
import subprocess
import tempfile
from dataclasses import asdict, dataclass, field
from datetime import date, datetime

EMPTY = {"", "NA", "N/A", "NOT APPLICABLE", "NIL", ","}
SECTION = re.compile(r"^\s*[A-K]\.\s+[A-Z]")


class PdfUnavailable(RuntimeError):
    pass


def available() -> bool:
    return shutil.which("pdftotext") is not None


def pdf_text(data: bytes) -> str:
    try:
        with tempfile.NamedTemporaryFile(suffix=".pdf") as f:  # deleted on close
            f.write(data)
            f.flush()
            out = subprocess.run(
                ["pdftotext", "-layout", "-enc", "UTF-8", "-l", "6", f.name, "-"],
                capture_output=True, timeout=20, check=True,
            )
    except FileNotFoundError as exc:
        raise PdfUnavailable("pdftotext is not installed") from exc
    except (subprocess.CalledProcessError, subprocess.TimeoutExpired) as exc:
        raise ValueError("PDF could not be read") from exc
    return out.stdout.decode("utf-8", errors="ignore")


@dataclass
class BgdData:
    application_id: str | None = None
    registration_date: date | None = None
    ivac_mission: str | None = None
    surname: str | None = None
    given_name: str | None = None
    gender: str | None = None
    date_of_birth: date | None = None
    place_of_birth: str | None = None
    marital_status: str | None = None
    nid_number: str | None = None
    passport_number: str | None = None
    passport_issue_date: date | None = None
    passport_issue_place: str | None = None
    passport_expiry_date: date | None = None
    phone: str | None = None
    email: str | None = None
    present_address: str | None = None
    permanent_address: str | None = None
    father_name: str | None = None
    mother_name: str | None = None
    spouse_name: str | None = None
    occupation: str | None = None
    visa_type: str | None = None
    visa_type_raw: str | None = None
    visa_entries: str | None = None
    visa_period: str | None = None
    expected_journey_date: date | None = None
    port_of_arrival: str | None = None
    port_of_exit: str | None = None
    places_to_visit: str | None = None
    missing: list[str] = field(default_factory=list)

    def as_dict(self) -> dict:
        return asdict(self)


def _value(text: str, label: str) -> str | None:
    """First value printed after ``label`` (a regex) on the same line."""
    m = re.search(rf"{label}[ \t]{{2,}}(\S(?:.*?\S)?)(?=[ \t]{{3,}}|[ \t]*$)", text, re.MULTILINE)
    if not m:
        return None
    v = re.sub(r"\s+", " ", m.group(1)).strip()
    return None if v.upper() in EMPTY else v


def _date(v: str | None) -> date | None:
    if not v:
        return None
    for fmt in ("%d-%b-%Y", "%d/%m/%Y", "%d-%m-%Y"):
        try:
            return datetime.strptime(v.strip().title(), fmt).date()
        except ValueError:
            continue
    return None


def _block(lines: list[str], start: str, stop: re.Pattern[str]) -> str | None:
    """A multi-line value (address) printed in one column, starting at the ``start`` label."""
    for i, line in enumerate(lines):
        m = re.match(rf"^(\s*{start}[ \t]{{2,}})\S", line)
        if not m:
            continue
        col = len(m.group(1))
        parts = []
        for j, cur in enumerate(lines[i:]):
            if j and (stop.search(cur) or SECTION.match(cur)):
                break
            if len(cur) <= col or (j and cur[:col].strip() not in ("", "Address")):
                continue
            piece = re.split(r"\s{3,}", cur[col:].strip())[0].strip()
            if piece:
                parts.append(piece)
        joined = ", ".join(parts)
        return joined or None
    return None


def _gender(v: str | None) -> str | None:
    v = (v or "").upper()
    return {"MALE": "male", "FEMALE": "female"}.get(v, "other" if v else None)


def _marital(v: str | None) -> str | None:
    v = (v or "").upper()
    if v in ("SINGLE", "UNMARRIED", "NEVER MARRIED"):
        return "single"
    if v.startswith("WIDOW"):
        return "widowed"
    return {"MARRIED": "married", "DIVORCED": "divorced"}.get(v)


def _visa(v: str | None) -> str | None:
    v = (v or "").upper()
    if not v:
        return None
    for key, kind in (("ATTENDANT", "medical_attendant"), ("MEDICAL", "medical"),
                      ("TOURIST", "tourist"), ("BUSINESS", "business"),
                      ("STUDENT", "student"), ("ENTRY", "entry")):
        if key in v:
            return kind
    return "other"


def parse(text: str) -> BgdData:
    lines = text.splitlines()
    d = BgdData()

    m = re.search(r"Application Id\s*:\s*([A-Z0-9]{6,20})", text)
    d.application_id = m.group(1) if m else None
    m = re.search(r"Web Registration Date\s*:\s*(\d{2}-[A-Z]{3}-\d{4})", text)
    d.registration_date = _date(m.group(1)) if m else None
    m = re.search(r"^\s*((?:ASST\.? |ASSISTANT )?HIGH COMMISSION OF INDIA.*?|"
                  r"(?:CONSULATE|EMBASSY) .*?INDIA.*?)\s*$", text, re.MULTILINE)
    d.ivac_mission = re.sub(r"\s+", " ", m.group(1)) if m else None

    d.surname = _value(text, r"Surname \(As in Passport\)")
    d.given_name = _value(text, r"Given Name \(As in Passport\)")
    d.gender = _gender(_value(text, r"Gender"))
    d.date_of_birth = _date(_value(text, r"Date of Birth"))
    d.place_of_birth = _value(text, r"Place of Birth Town/City")
    d.marital_status = _marital(_value(text, r"Marital Status"))
    nid = _value(text, r"Citizenship /\s?National ID No")
    d.nid_number = re.sub(r"\D", "", nid) if nid and re.search(r"\d{10}", nid) else None

    d.passport_number = _value(text, r"Passport No\.")
    d.passport_issue_date = _date(_value(text, r"Date of Issue \( ?dd/mm/yyyy ?\)"))
    d.passport_issue_place = _value(text, r"Place of Issue")
    d.passport_expiry_date = _date(_value(text, r"Date of Expiry \( ?dd/mm/yyyy ?\)"))

    d.phone = _value(text, r"Phone No") or _value(text, r"Mobile /\s?Cell No")
    email = _value(text, r"Email address")
    d.email = email.lower() if email and "@" in email else None
    d.present_address = _block(lines, "Present", re.compile(r"^\s*Permanent\b"))
    d.permanent_address = _block(lines, "Permanent", re.compile(r"^\s*D\.\s"))

    d.father_name = _value(text, r"Father's")
    d.mother_name = _value(text, r"Mother's")
    d.spouse_name = _value(text, r"Spouse")
    d.occupation = _value(text, r"Present Occupation")

    d.visa_type_raw = _value(text, r"Type Of Visa Required")
    d.visa_type = _visa(d.visa_type_raw)
    d.visa_entries = _value(text, r"No of Entries")
    d.visa_period = _value(text, r"Period of Visa \( ?Month ?\)")
    d.expected_journey_date = _date(_value(text, r"Expected Date of Journey"))
    d.port_of_arrival = _value(text, r"Port Of Arrival")
    d.port_of_exit = _value(text, r"Port of Exit")
    d.places_to_visit = _value(text, r"Places to be Visited")

    required = ("application_id", "surname", "given_name", "gender", "date_of_birth",
                "passport_number", "passport_expiry_date", "visa_type")
    d.missing = [k for k in required if getattr(d, k) in (None, "")]
    return d


def looks_like_bgd(d: BgdData) -> bool:
    return bool(d.application_id or (d.passport_number and d.surname))
